-- ============================================================================
-- 秒杀库存预扣脚本（第20课时 · 最终版的第一步）
-- ============================================================================
-- KEYS[1] = 库存 key，例如 mall:stock:product:1        （value 是字符串数字）
-- ARGV[1] = 本次要扣减的数量（正整数）
--
-- 返回值约定（三个状态，缺一不可）：
--   >= 0   预扣成功，返回值是扣减后【剩余】的库存
--   -1     库存不足，本次请求应当被拒绝
--   -2     库存未预热（Redis 里根本没有这个 key）
--
-- 为什么必须把"判断"和"扣减"写进同一段脚本？
-- ---------------------------------------------------------------------------
-- 如果拆成两条命令发：
--     10:00:00.001  请求A  GET  -> 10     判断"够"
--     10:00:00.002  请求B  GET  -> 10     判断"够"   ← 两条命令之间被插进来了
--     10:00:00.003  请求A  DECRBY 1 -> 9
--     10:00:00.004  请求B  DECRBY 1 -> 8
--   结果：卖出 2 件、库存只减了 1 件 —— 这就是超卖。
--   注意这和 V1 在 Java 层"先查后改"是【同一个 BUG】，只是把位置从 JVM 挪到了
--   Redis 客户端；网络往返一样会制造窗口，Redis 本身快并不能救你。
--
-- Redis 用【单线程】执行 Lua 脚本：脚本从第一行跑到最后一行期间，
-- 不会有任何其他命令插进来。于是"判断 + 扣减"变成了一个不可分割的原子操作，
-- 这才是 Lua 在这里的真正价值 —— 它不是"更快的命令"，而是"多条命令的原子打包"。
--
-- 三个状态为什么必须分开？
-- ---------------------------------------------------------------------------
-- "未预热"（-2）绝不能当成"库存为 0"（-1）处理：
--   -1 → 业务上正常的结果，告诉用户"卖完了"
--   -2 → 是【故障】：缓存数据没准备好（预热漏了、Redis 重启丢数据、
--        key 被误删）。此时如果当成 0，用户看到的是"卖完了"，
--        而真实原因是"库存数据没加载"，问题会被藏起来，排查时完全摸不着头绪。
--   所以这里显式返回 -2，让调用方立刻用醒目的错误提示出来。
--
-- 补充：为什么是"宁可少卖不可超卖"？
-- ---------------------------------------------------------------------------
-- 秒杀场景下 Redis 与 DB 是两份数据，Redis 扣成功、DB 兜底拦下时，
-- 消费端会把库存【还回】Redis（见 OrderMqConsumer 的补偿分支）。
-- 也就是允许"暂时少卖一件、随后补回"，但绝不允许库存变成负数。
-- ============================================================================

local stock = redis.call('GET', KEYS[1])

-- key 不存在：Redis 返回的是 boolean false，不是 nil，这一点容易踩
if stock == false then
    return -2
end

local current = tonumber(stock)
local quantity = tonumber(ARGV[1])

-- 值被写坏成非数字（人工改错、序列化不一致）同样按"未预热"处理，宁可报错也别算错
if current == nil or quantity == nil or quantity <= 0 then
    return -2
end

if current < quantity then
    return -1
end

-- DECRBY 返回扣减后的结果，直接透传给调用方
return redis.call('DECRBY', KEYS[1], quantity)
