-- ============================================================================
-- 秒杀库存回补脚本（第20课时 · V8 补偿专用）
-- ============================================================================
-- KEYS[1] = 库存 key，例如 mall:stock:product:1
-- ARGV[1] = 本次要回补的数量（正整数）
--
-- 返回值约定：
--   >= 0   回补成功，返回值是回补后的库存
--   -2     库存 key 不存在（未预热 / Redis 数据丢失），拒绝回补
--
-- 为什么回补必须用 Lua，而不是直接 INCRBY？
-- ---------------------------------------------------------------------------
-- INCRBY 单条命令本身是原子的，不存在"读-判-写"竞态 —— 这不是用它 Lua 的原因。
-- 真正的原因是：INCRBY 在 key 不存在时会【从 0 开始创建 key】。
--   场景：Redis 重启丢了库存数据 → 本该处于"未预热"故障态 →
--         此时一条旧消息被 DB 兜底拦下触发回补 → INCRBY 凭空造出一个
--         "库存 = 回补数量"的假 key → 故障被掩盖，排查时完全摸不着头绪。
-- 所以这里先 EXISTS 检查：数据不在就显式拒绝（-2），让调用方告警，
-- 宁可少补一件（人工介入），也不把故障藏起来。
--
-- 更进一步（思考题）：预热时可以额外记录一个"初始库存" key，
-- 回补后超过初始库存就说明多补了 —— 教学代码里用"补偿幂等标记"挡住
-- 重复回补（见 MqIdempotentGuard.tryMarkCompensated），生产上还可以再加对账。
-- ============================================================================

if redis.call('EXISTS', KEYS[1]) == 0 then
    return -2
end

return redis.call('INCRBY', KEYS[1], ARGV[1])
